package com.omya.hospital.service;

import com.itextpdf.kernel.colors.ColorConstants;
import com.itextpdf.kernel.pdf.PdfDocument;
import com.itextpdf.kernel.pdf.PdfWriter;
import com.itextpdf.layout.Document;
import com.itextpdf.layout.element.Paragraph;
import com.itextpdf.layout.properties.TextAlignment;
import com.omya.hospital.dto.PatientHistoryResponse;
import com.omya.hospital.entity.Bill;
import com.omya.hospital.entity.Medicine;
import com.omya.hospital.repository.BillRepository;
import com.omya.hospital.repository.MedicineRepository;
import java.io.ByteArrayOutputStream;
import java.time.format.DateTimeFormatter;
import org.springframework.stereotype.Service;

@Service
public class PdfService {

  private final BillRepository billRepo;

  private final MedicineRepository medicineRepo;

  private static final String LINE =
    "-------------------------------------------";

  private static final DateTimeFormatter DATE_FORMAT =
    DateTimeFormatter.ofPattern("dd-MM-yyyy HH:mm");

  public PdfService(BillRepository billRepo, MedicineRepository medicineRepo) {
    this.billRepo = billRepo;

    this.medicineRepo = medicineRepo;
  }

  private void header(Document document, String title) {
    document.add(
      new Paragraph("OMYA HOSPITAL")

        .setBold()

        .setFontSize(22)

        .setFontColor(ColorConstants.BLUE)

        .setTextAlignment(TextAlignment.CENTER)
    );

    document.add(
      new Paragraph(title)

        .setBold()

        .setFontSize(15)
    );

    document.add(new Paragraph(LINE));
  }

  private void footer(Document document) {
    document.add(new Paragraph(LINE));

    document.add(new Paragraph("Get Well Soon").setItalic());

    document.add(
      new Paragraph("Hospital Copy")

        .setItalic()

        .setTextAlignment(TextAlignment.RIGHT)
    );

    document.add(new Paragraph("Thank You").setBold());

    document.add(
      new Paragraph("Generated By OMYA ERP").setTextAlignment(
        TextAlignment.RIGHT
      )
    );
  }

  public byte[] patientPdf(PatientHistoryResponse history) {
    try {
      ByteArrayOutputStream out = new ByteArrayOutputStream();

      Document document = new Document(new PdfDocument(new PdfWriter(out)));

      header(
        document,

        "PATIENT SUMMARY"
      );

      document.add(
        new Paragraph(
          "Patient Name : " +
            history
              .getPatient()

              .getPatientName()
        )
      );

      document.add(
        new Paragraph(
          "UHID : " +
            history
              .getPatient()

              .getUhid()
        )
      );

      document.add(
        new Paragraph(
          "Age : " +
            history
              .getPatient()

              .getAge()
        )
      );

      document.add(
        new Paragraph(
          "Appointments : " +
            history
              .getAppointments()

              .size()
        )
      );

      document.add(
        new Paragraph(
          "Prescriptions : " +
            history
              .getPrescriptions()

              .size()
        )
      );

      document.add(
        new Paragraph(
          "Lab Reports : " +
            history
              .getLabTests()

              .size()
        )
      );

      document.add(
        new Paragraph(
          "Bills : " +
            history
              .getBills()

              .size()
        )
      );

      document.add(
        new Paragraph(
          "Admissions : " +
            history
              .getAdmissions()

              .size()
        )
      );

      footer(document);

      document.close();

      return out.toByteArray();
    } catch (Exception e) {
      throw new com.omya.hospital.exception.BusinessRuleException(
        "PATIENT PDF FAILED",

        e
      );
    }
  }

  public byte[] billPdf(Long id) {
    try {
      Bill bill = billRepo

        .findById(id)

        .orElseThrow(() ->
          new com.omya.hospital.exception.BusinessRuleException(
            "BILL NOT FOUND"
          )
        );

      Medicine medicine = medicineRepo

        .findByBarcode(bill.getMedicineBarcode())

        .orElse(null);

      String amount = String.format(
        "Rs %.2f",

        bill.getTotalAmount()
      );

      ByteArrayOutputStream out = new ByteArrayOutputStream();

      Document document = new Document(new PdfDocument(new PdfWriter(out)));

      header(
        document,

        "MEDICAL BILL"
      );

      document.add(
        new Paragraph("INVOICE : BILL-" + bill.getId())

          .setBold()

          .setFontSize(13)

          .setFontColor(ColorConstants.DARK_GRAY)
      );

      document.add(new Paragraph("Patient ID : " + bill.getPatientId()));

      document.add(
        new Paragraph("Appointment ID : " + bill.getAppointmentId())
      );

      if (medicine != null) {
        document.add(new Paragraph("Medicine : " + medicine.getMedicineName()));
      }

      document.add(
        new Paragraph("Medicine Barcode : " + bill.getMedicineBarcode())
      );

      document.add(new Paragraph("Quantity : " + bill.getQuantity()));

      document.add(new Paragraph("Total Amount : " + amount));

      document.add(
        new Paragraph(
          "Bill Time : " +
            bill
              .getBillTime()

              .format(DATE_FORMAT)
        )
      );

      footer(document);

      document.close();

      return out.toByteArray();
    } catch (Exception e) {
      throw new com.omya.hospital.exception.BusinessRuleException(
        "BILL PDF FAILED",

        e
      );
    }
  }
}
